export type LearnerContext = {
  displayName: string;
  ageGroup: "UNDER_14" | "FROM_14_TO_17" | "ADULT";
  learnerType?: string | null;
  grade?: number | null;
  schoolProfile?: string | null;
  program?: string | null;
  courseYear?: number | null;
  vocational?: string | null;
  drivingCategory?: string | null;
};

const LEARNER_LABEL: Record<string, string> = {
  SCHOOL: "ученик",
  LANGUAGE_SCHOOL: "ученик в езикова гимназия",
  VOCATIONAL: "ученик в професионална гимназия",
  UNIVERSITY: "студент",
  APPLICANT: "кандидат-студент",
  DRIVING: "кандидат за шофьорска книжка",
  SELF: "учи самостоятелно",
  OTHER: "учащ",
};

export function learnerContextBlock(c: LearnerContext) {
  const lines = [`Профил на учащия (използвай го, за да нагласиш нивото; не го споменавай без нужда):`];
  lines.push(`- Обръщение: ${c.displayName}`);
  lines.push(
    `- Възраст: ${c.ageGroup === "UNDER_14" ? "под 14 години" : c.ageGroup === "FROM_14_TO_17" ? "14–17 години" : "пълнолетен"}`,
  );
  if (c.learnerType) lines.push(`- Тип: ${LEARNER_LABEL[c.learnerType] ?? c.learnerType}`);
  if (c.grade) lines.push(`- Клас: ${c.grade}.`);
  if (c.schoolProfile) lines.push(`- Профил/паралелка: ${c.schoolProfile}`);
  if (c.vocational) lines.push(`- Професия/специалност: ${c.vocational}`);
  if (c.program) lines.push(`- Специалност във висше училище: ${c.program}`);
  if (c.courseYear) lines.push(`- Курс: ${c.courseYear}`);
  if (c.drivingCategory) lines.push(`- Шофьорска категория: ${c.drivingCategory}`);
  return lines.join("\n");
}

export type LessonContext = {
  title: string;
  subject: string;
  course: string;
  grade: number | null;
  text: string;
};

/** Текст на урока от платформата — подава се като основа (ограничен по дължина). */
export function lessonContextBlock(l: LessonContext) {
  const body = l.text.length > 24000 ? l.text.slice(0, 24000) + "\n…(съкратено)" : l.text;
  return `Ученикът е отворил урок от платформата BG LEARN. Използвай го като основа на обясненията си.
<lesson title="${l.title.replace(/"/g, "'")}" subject="${l.subject}" course="${l.course.replace(/"/g, "'")}"${l.grade ? ` grade="${l.grade}"` : ""}>
${body}
</lesson>`;
}
